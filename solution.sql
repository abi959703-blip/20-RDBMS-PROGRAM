-- 1. CREATE EMPLOYEE TABLE

CREATE TABLE EMPLOYEE (
    EMPLOYEE_ID NUMBER PRIMARY KEY,
    EMPLOYEE_NAME VARCHAR2(50),
    DEPARTMENT VARCHAR2(30),
    SALARY NUMBER
);


-- 2. INSERT SAMPLE RECORDS

INSERT INTO EMPLOYEE VALUES (101, 'Arun', 'CSE', 30000);
INSERT INTO EMPLOYEE VALUES (102, 'Priya', 'ECE', 35000);

COMMIT;


-- 3. ENABLE SERVER OUTPUT

SET SERVEROUTPUT ON;


-- 4. CREATE TRIGGER

CREATE OR REPLACE TRIGGER EMPLOYEE_INSERT_TRIGGER
AFTER INSERT ON EMPLOYEE
FOR EACH ROW
BEGIN
    DBMS_OUTPUT.PUT_LINE(
        'New employee inserted successfully. Employee ID: '
        || :NEW.EMPLOYEE_ID
    );
END;
/


